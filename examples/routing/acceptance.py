"""Fixed-seed acceptance boards of the router workflow (change c0370).

``script(seed=, layers=, parts=)`` returns the text of a design script: ``parts`` two-pad passives of the
built-in catalog on a grid, on a two- or four-layer board. Pads 1 are paired into signal nets inside
blocks of eight cells, in an order drawn from ``seed``, so the nets cross locally; pads 2 go to ``VIN`` or
``GND`` (declared as one supply), which carry a ground zone (``B.Cu`` on two layers, ``In1.Cu`` and a
``VIN`` zone on ``In2.Cu`` on four). The same arguments always give the same bytes: the generator uses its
own integer mixer (SplitMix64), not ``random``. Nothing is taken from another board.

Write one with ``python examples/routing/acceptance.py --seed 1 --layers 2 --parts 40 --out board.py`` and
build it with ``fenolite build board.py --out build/acceptance --confirm``.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

LAYERS = (2, 4)
MIN_PARTS, MAX_PARTS = 4, 160
BLOCK = 8
"""Cells whose pads 1 are paired among themselves."""
PITCH_X_UM, PITCH_Y_UM = 5000, 4000
"""Cell pitch in micrometres: wider than the largest footprint (0805) with its courtyard."""
MARGIN_UM = 3000
MASK = (1 << 64) - 1

HEADER = """\
# SPDX-License-Identifier: CC0-1.0
# Authored for Fenolite as a router acceptance board; generated by examples/routing/acceptance.py.
"""


class Mixer:
    """SplitMix64: a fixed integer sequence from a seed, the same on every Python version."""

    def __init__(self, seed: int) -> None:
        self.state = seed & MASK

    def next(self) -> int:
        self.state = (self.state + 0x9E3779B97F4A7C15) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        return z ^ (z >> 31)

    def below(self, n: int) -> int:
        """An integer in ``range(n)`` without modulo bias."""
        limit = (1 << 64) - (1 << 64) % n
        while True:
            value = self.next()
            if value < limit:
                return value % n

    def shuffled(self, items: list[int]) -> list[int]:
        out = list(items)
        for i in range(len(out) - 1, 0, -1):
            j = self.below(i + 1)
            out[i], out[j] = out[j], out[i]
        return out


def grid(parts: int) -> tuple[int, int]:
    """Columns and rows of the cell grid: about 5:4 wide, every part in one cell."""
    cols = max(2, math.isqrt(parts * 5 // 4 - 1) + 1)
    return cols, -(-parts // cols)


def _mm(um: int) -> str:
    return f'mm("{um // 1000}.{um % 1000:03d}")'


def script(*, seed: int, layers: int, parts: int) -> str:
    """The design script of one acceptance board; ``ValueError`` for arguments outside the bounds."""
    if isinstance(seed, bool) or not isinstance(seed, int) or not 0 <= seed <= MASK:  # pyright: ignore[reportUnnecessaryIsInstance]
        raise ValueError(f"seed must be an integer in 0..2**64-1, not {seed!r}")
    if layers not in LAYERS:
        raise ValueError(f"layers must be one of {LAYERS}, not {layers!r}")
    if isinstance(parts, bool) or not isinstance(parts, int) or not MIN_PARTS <= parts <= MAX_PARTS:  # pyright: ignore[reportUnnecessaryIsInstance]
        raise ValueError(f"parts must be an integer in {MIN_PARTS}..{MAX_PARTS}, not {parts!r}")
    rng = Mixer(seed)
    cols, rows = grid(parts)
    width = cols * PITCH_X_UM + 2 * MARGIN_UM
    height = rows * PITCH_Y_UM + 2 * MARGIN_UM
    name = f"route_acceptance_s{seed}_l{layers}_p{parts}"
    lines = [
        HEADER.rstrip("\n"),
        f'"""Router acceptance board: seed {seed}, {layers} copper layers, {parts} parts."""',
        "",
        "from fenolite.dsl import Design, Net, Part, Power, connect, mm",
        "",
        f'design = Design("{name}")',
        f"design.board({_mm(width)}, {_mm(height)}, copper={layers})",
        'vin, gnd = Net("VIN"), Net("GND")',
        "",
    ]
    refs: list[str] = []
    for index in range(parts):
        capacitor = rng.below(3) == 0
        ref = f"C{index + 1}" if capacitor else f"R{index + 1}"
        refs.append(ref)
        symbol, footprint, value = (
            ("Capacitor", "Chip_0805", "100nF") if capacitor else ("Resistor", "Chip_0603", "1k")
        )
        lines.append(
            f'{ref.lower()} = Part("{ref}", "Fenolite:{symbol}", '
            f'footprint="Fenolite:{footprint}", value="{value}")'
        )
    lines.append(f"design.add({', '.join(ref.lower() for ref in refs)})")
    lines.append("")
    signals: list[list[int]] = []
    for start in range(0, parts, BLOCK):
        order = rng.shuffled(list(range(start, min(start + BLOCK, parts))))
        pairs = [order[i : i + 2] for i in range(0, len(order) - 1, 2)]
        if len(order) % 2:
            if pairs:
                pairs[-1].append(order[-1])
            else:  # a lone last cell joins the previous block's last net
                signals[-1].append(order[-1])
        signals.extend(pairs)
    for number, members in enumerate(signals, start=1):
        pads = ", ".join(f"{refs[i].lower()}[1]" for i in members)
        lines.append(f'connect(Net("SIG{number}"), {pads})')
    supply = [rng.below(2) for _ in range(parts)]
    if not any(supply):
        supply[0] = 1
    if all(supply):
        supply[0] = 0
    lines.append(f"connect(vin, {', '.join(f'{refs[i].lower()}[2]' for i in range(parts) if supply[i])})")
    lines.append(f"connect(gnd, {', '.join(f'{refs[i].lower()}[2]' for i in range(parts) if not supply[i])})")
    lines += [
        "design.add(Power(vin, gnd))",
        "",
        'design.rules.netclass("PWR", clearance=mm("0.2"), track_width=mm("0.4"), nets=(vin, gnd))',
        "design.rules.minimum(",
        '    clearance=mm("0.15"), track_width=mm("0.15"), via_diameter=mm("0.45"), via_drill=mm("0.2"),',
        '    hole_size=mm("0.3"), edge_clearance=mm("0.3"),',
        ")",
        'design.rules.minimum(clearance=mm("0.2"), track_width=mm("0.4"), netclass="PWR")',
    ]
    if layers == 2:
        lines.append('design.zone(gnd, layers=("B.Cu",), connection="solid")')
    else:
        lines.append('design.zone(gnd, layers=("In1.Cu",), connection="solid")')
        lines.append('design.zone(vin, layers=("In2.Cu",), connection="solid")')
    lines.append("")
    for index, ref in enumerate(refs):
        col, row = index % cols, index // cols
        x = MARGIN_UM + col * PITCH_X_UM + PITCH_X_UM // 2
        y = MARGIN_UM + row * PITCH_Y_UM + PITCH_Y_UM // 2
        rot = 90 * rng.below(2)
        lines.append(f"{ref.lower()}.place({_mm(x)}, {_mm(y)}, rot={rot})")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write one fixed-seed router acceptance board script.")
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--layers", type=int, choices=LAYERS, required=True)
    parser.add_argument("--parts", type=int, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    args.out.write_text(script(seed=args.seed, layers=args.layers, parts=args.parts), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
